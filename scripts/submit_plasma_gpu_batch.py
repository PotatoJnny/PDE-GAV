#!/usr/bin/env python3
"""Prepare and submit the six approved GPU runs with a durable submission ledger.

No cancellation is performed here. An uncertain submission is never retried:
inspect the preserved receipt and scheduler before any recovery action.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
import json
import os
from pathlib import Path
import re
import shlex
import stat
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT), str(ROOT / "src"), str(ROOT / "scripts")]
from pde_agent_verifier_solver.engine.checkpoint_store import atomic_json, run_writer_lock
from scripts.ns_slurm_continuation import PLASMA_L40S_PARTITIONS

# Site-specific Slurm account; see docs/SITE_CONFIGURATION.md.
SLURM_ACCOUNT = os.environ.get("PDE_GAV_SLURM_ACCOUNT", "${PDE_GAV_SLURM_ACCOUNT}")

NAMES = tuple(f"{equation}-{arm}" for equation in ("strong", "weak", "artemis") for arm in ("sol", "astra"))
RUNTIME_SHA256 = "13167b35b7f31ec79358bae623229a0bd43dd01364805af5d16e6c0c12f01962"


def digest(path):
    value = sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def read(path):
    return json.loads(Path(path).read_text())


def checked_file(path, expected):
    path = Path(path)
    if path.is_symlink() or not path.is_file() or digest(path) != expected:
        raise ValueError("pinned input changed: " + str(path))
    return path


def clean_source(root=ROOT):
    root = Path(root)
    def git(*args):
        return subprocess.check_output(["git", "-C", str(root), *args], text=True).strip()
    if git("status", "--porcelain", "--untracked-files=all"):
        raise ValueError("submission requires a clean committed frozen source")
    return git("rev-parse", "HEAD")


def resources(equation):
    if equation not in ("strong", "weak", "artemis"):
        raise ValueError("unknown equation")
    artemis = equation == "artemis"
    return {"gpu_count": 4, "cpus": 24, "memory": "64G" if artemis else "128G",
            "time": "06:00:00" if artemis else "12:00:00",
            "shutdown_margin_seconds": 600 if artemis else 2400, "max_segments": 12}


def slurm_text(site, site_path):
    # No expansions in SBATCH paths; paths are generated by this deployment.
    for key in ("source_root", "run_root", "python"):
        if any(char.isspace() for char in str(site[key])):
            raise ValueError("Slurm deployment paths must not contain whitespace")
    root = Path(site["source_root"])
    return f'''#!/usr/bin/env bash
#SBATCH --account={site['account']}
#SBATCH --partition={site['partition']}
#SBATCH --qos={site['qos']}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --gres=gpu:l40s:4
#SBATCH --cpus-per-task=24
#SBATCH --mem={site['memory']}
#SBATCH --time={site['time']}
#SBATCH --signal=B:USR1@600
#SBATCH --job-name=pde-{site['arm_name']}
#SBATCH --output={site['run_root']}/slurm-%j.out
#SBATCH --error={site['run_root']}/slurm-%j.err
set -eo pipefail
umask 077
test -n "${{SLURM_JOB_ID:-}}"
test -n "${{SLURM_TMPDIR:-}}"
if ! type module >/dev/null 2>&1 && [[ -r /etc/profile.d/modules.sh ]]; then
  source /etc/profile.d/modules.sh
fi
if ! module load scipy-stack pytest; then
  echo 'Cluster modules unavailable; using the existing configured Python environment.' >&2
fi
source "${{PDE_GAV_VENV}}/bin/activate"
set -u
PLASMA_SOURCE={shlex.quote(str(root))}
PLASMA_SITE=${{1:-{shlex.quote(str(site_path))}}}
export PYTHONPATH="$PLASMA_SOURCE:$PLASMA_SOURCE/src:$PLASMA_SOURCE/scripts"
export PYTHONPYCACHEPREFIX="$SLURM_TMPDIR/pde-gav-pycache"
export PYTHONDONTWRITEBYTECODE=1 PYTHONNOUSERSITE=1 PYTHONUNBUFFERED=1 PYTHONFAULTHANDLER=1
export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 NUMEXPR_NUM_THREADS=1
export CUDA_DEVICE_ORDER=PCI_BUS_ID CUBLAS_WORKSPACE_CONFIG=:4096:8
export PDE_AGENT_WORKER_GPU_DEVICES=0,1 PDE_CONTROLLER_GPU_DEVICE=2
export NS_CONTINUATION_SLURM_ACCOUNT={site['account']} NS_CONTINUATION_SLURM_QOS={site['qos']}
export NS_CONTINUATION_SLURM_GPU_TYPE=l40s NS_CONTINUATION_SLURM_PARTITION={site['partition']}
unset PYTHONOPTIMIZE
cd -- "$PLASMA_SOURCE"
exec {shlex.quote(site['python'])} scripts/run_plasma_gpu_segment.py --site "$PLASMA_SITE"
'''


def prepare(config_directory, output, *, run_parent, python, codex_binary, auth_file):
    from plasma_gpu_campaign import load_config, static_check
    revision = clean_source()
    output, config_directory = Path(output).resolve(), Path(config_directory).resolve()
    if output.exists():
        raise FileExistsError("deployment already exists; do not replace its submission records")
    runtime, auth, python = Path(codex_binary).resolve(), Path(auth_file), Path(python).absolute()
    checked_file(runtime, RUNTIME_SHA256)
    if not os.access(runtime, os.X_OK) or not os.access(python, os.X_OK):
        raise ValueError("runtime and Python must be executable")
    if auth.is_symlink() or not auth.is_file() or stat.S_IMODE(auth.stat().st_mode) != 0o600:
        raise ValueError("auth locator must identify an existing mode-600 regular file")
    migration = read(config_directory / "migration.json")
    if {row["name"] for row in migration["arms"]} != set(NAMES):
        raise ValueError("the prepared configuration set must contain all six arms")
    indexed = {row["name"]: row for row in migration["arms"]}
    inputs = []
    for name in NAMES:
        entry = indexed[name]
        path = checked_file(entry["config"], entry["sha256"])
        config = load_config(path)
        static_check(config)
        run_root = Path(run_parent).resolve() / config["campaign_id"]
        if run_root.exists():
            raise FileExistsError("new experiment output already exists: " + str(run_root))
        inputs.append((name, path, config, run_root))
    output.mkdir(parents=True, mode=0o700)
    names = subprocess.check_output(["git", "-C", str(ROOT), "ls-files", "-z"]).decode().split("\0")
    source_manifest = output / "source-manifest.json"
    files = []
    for name in sorted(filter(None, names)):
        path = ROOT / name
        if path.is_symlink() or not path.is_file():
            raise ValueError("source manifest requires regular tracked files: " + name)
        files.append({"path": name, "sha256": digest(path)})
    atomic_json(source_manifest, {"schema": "pde_gav_frozen_source_v1", "revision": revision, "files": files})
    plan = {"schema": "pde_gav_six_gpu_submission_v1", "status": "prepared",
            "source_root": str(ROOT), "source_revision": revision, "entries": []}
    for name, config_path, config, run_root in inputs:
        directory = output / name
        directory.mkdir(mode=0o700)
        run_root.mkdir(parents=True, mode=0o700)  # Slurm log parent only; no campaign state.
        site_path, script_path = directory / "site.json", directory / "run.slurm"
        site = {"schema": "pde_gav_plasma_gpu_site_v1", "arm_name": name,
                "source_root": str(ROOT), "source_revision": revision,
                "source_manifest": str(source_manifest), "source_manifest_sha256": digest(source_manifest),
                "config_path": str(config_path), "config_sha256": digest(config_path),
                "run_root": str(run_root), "python": str(python), "codex_binary": str(runtime),
                "codex_sha256": RUNTIME_SHA256, "auth_file": str(auth), "slurm_script": str(script_path),
                "account": SLURM_ACCOUNT, "partition": PLASMA_L40S_PARTITIONS, "qos": "normal",
                **resources(config["equation"])}
        script_path.write_text(slurm_text(site, site_path))
        script_path.chmod(0o700)
        subprocess.run(["bash", "-n", str(script_path)], check=True)
        site["slurm_script_sha256"] = digest(script_path)
        atomic_json(site_path, site)
        plan["entries"].append({"name": name, "script": str(script_path), "site": str(site_path),
                                "script_sha256": digest(script_path), "site_sha256": digest(site_path)})
    atomic_json(output / "plan.json", plan)
    return plan


def submit(plan_path):
    from run_plasma_gpu_segment import verify_site
    plan_path = Path(plan_path).resolve()
    plan = read(plan_path)
    if (plan.get("schema") != "pde_gav_six_gpu_submission_v1" or plan.get("status") != "prepared"
            or {row["name"] for row in plan["entries"]} != set(NAMES) or len(plan["entries"]) != 6):
        raise ValueError("complete prepared six-arm plan required")
    if clean_source() != plan["source_revision"] or str(ROOT) != plan["source_root"]:
        raise ValueError("submit from the exact frozen source")
    for row in plan["entries"]:
        checked_file(row["site"], row["site_sha256"])
        checked_file(row["script"], row["script_sha256"])
        verify_site(Path(row["site"]))
    ledger_path = plan_path.parent / "submissions.json"
    with run_writer_lock(plan_path.parent):
        if ledger_path.exists():
            raise FileExistsError("submission ledger exists; inspect it, never blindly resubmit")
        ledger = {"schema": "pde_gav_six_gpu_submission_receipt_v1", "plan_sha256": digest(plan_path),
                  "status": "submitting", "jobs": [], "old_jobs_cancelled": False}
        atomic_json(ledger_path, ledger)
        for row in plan["entries"]:
            ledger["pending_arm"] = row["name"]
            atomic_json(ledger_path, ledger)
            environment = {key: value for key, value in os.environ.items() if not key.startswith("NS_CONTINUATION_")}
            try:
                result = subprocess.run(["sbatch", "--parsable", row["script"]],
                    cwd=ROOT, env=environment, text=True, capture_output=True, timeout=45)
                match = re.fullmatch(r"([1-9][0-9]*)(?:;[A-Za-z0-9_.-]+)?", result.stdout.strip())
                if result.returncode or match is None:
                    raise RuntimeError("sbatch did not return a confirmed job ID: " + result.stderr[:1000])
            except BaseException as error:
                ledger.update(status="submission_unknown", error=str(error))
                atomic_json(ledger_path, ledger)
                raise
            job = {"name": row["name"], "job_id": match[1], "script": row["script"], "site": row["site"]}
            ledger["jobs"].append(job)
            ledger.pop("pending_arm", None)
            atomic_json(ledger_path, ledger)
            print(json.dumps(job), flush=True)
        ledger["status"] = "all_six_submitted"
        atomic_json(ledger_path, ledger)
    return ledger


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    make = commands.add_parser("prepare")
    for name in ("config-directory", "output", "run-parent", "python", "codex-binary", "auth-file"):
        make.add_argument("--" + name, type=Path, required=True)
    launch = commands.add_parser("submit")
    launch.add_argument("--plan", type=Path, required=True)
    args = vars(parser.parse_args(argv))
    command = args.pop("command")
    result = prepare(**args) if command == "prepare" else submit(args["plan"])
    print(json.dumps({"status": result["status"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
