def __getattr__(name: str):
    module_name = _LEGACY_EXPORTS.get(name)
    if module_name is None:
        raise AttributeError(name)
    warn(
        f"sdk.{name} belongs to the legacy formal Macro surface; new PDEs use "
        "ProblemProgram, GeneratorProgram, TaskProgram, and EvaluationProgram",
        DeprecationWarning,
        stacklevel=2,
    )
    value = getattr(import_module(module_name, __name__), name)
    globals()[name] = value
    return value
